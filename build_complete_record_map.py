    for r in records:
        x,y,z,t=r['box'];color='#2563eb' if r['complete'] else '#94a3b8';dash='' if r['complete'] else 'stroke-dasharray="7 5"'
        if r['record_id']==RID and r['complete']:color='#b45309'
        out.append(f'<rect x="{x+xoff-2}" y="{y+yoff-2}" width="{z-x+4}" height="{t-y+4}" fill="none" stroke="{color}" stroke-width="3" {dash}/>')
        bx=28 if r['column']==0 else 1076;by=y+yoff+10
        out.append(f'<rect x="{bx}" y="{by}" width="52" height="32" rx="6" fill="{color}"/>')
        out.append(text(bx+26,by+23,r['label'],'', 'text-anchor="middle" fill="white" font-size="20" font-weight="700"'))
