def image_data(image):
    stream=io.BytesIO();image.save(stream,format='PNG')
    return 'data:image/png;base64,'+base64.b64encode(stream.getvalue()).decode()

def esc(text):return html.escape(str(text),quote=True)

def svg_start(width,height):
    return [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<style>text{font-family:Arial,sans-serif} .title{font-size:30px;font-weight:700;fill:#142f49}.sub{font-size:17px;fill:#49637a}</style>',
        f'<rect width="{width}" height="{height}" fill="#f5f7fb"/>']

def text(x,y,value,cls='sub',attrs=''):
    return f'<text x="{x}" y="{y}" class="{cls}" {attrs}>{esc(value)}</text>'

def detect_complete(image):
    engine=RapidOCR(intra_op_num_threads=2,inter_op_num_threads=1,text_score=0)
    result=[];count=0
    for index,block in enumerate(blocks(image)):
        rid,raw=read_header(engine,image.crop(block['box']))
        complete=bool(rid) and not block['open_bottom']
        if complete:count+=1
        result.append(dict(block_index=index,record_id=rid,header_ocr=raw,complete=complete,
            label='R'+str(count) if complete else 'P'+str(sum(not r['complete'] for r in result)+1),
            reason='Readable starting ID and closed lower rule' if complete else ('Open lower edge; continuation excluded' if block['open_bottom'] else 'Continuation without a starting record ID; excluded'),**block))
    return result

