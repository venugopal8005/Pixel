def numbered_field_svg(image,fields):
    # Separate original image strips vertically so labels do not cover glyphs.
    cuts=[534,552,570,587,604,621,638,655,672,689,706,724,736]
    out=svg_start(1480,1480)
    out += [text(38,43,'02 / Map every field number','title'),text(38,77,'R7 · Record 1802603511 · 37 output columns in the instruction-sheet order'),
        text(38,105,'Source-coordinate proposal. Original text rows are spaced apart below so labels remain readable.')]
    cursor=131;scale=3;xoff=60
    for row,(top,bottom) in enumerate(zip(cuts,cuts[1:])):
        if row==11:break # final band is blank; retained in the full original crop.
        yimage=cursor+23
        crop=image.crop((FRAME[0],top,FRAME[2],bottom))
        out.append(f'<image x="{xoff}" y="{yimage}" width="{crop.width*scale}" height="{crop.height*scale}" href="{image_data(crop)}"/>')
        for f in fields:
            for x,y,z,t in f['regions']:
                if y!=top:continue
                bx=xoff+(x-FRAME[0])*scale;bw=(z-x)*scale
                out.append(f'<rect x="{bx}" y="{yimage}" width="{bw}" height="{(bottom-top)*scale}" fill="none" stroke="{f["color"]}" stroke-width="1.8"/>')
                out.append(f'<rect x="{bx}" y="{cursor}" width="30" height="22" rx="4" fill="{f["color"]}"/>')
                out.append(text(bx+15,cursor+16,f'{f["number"]:02}','','text-anchor="middle" fill="white" font-size="16" font-weight="700"'))
        cursor=yimage+(bottom-top)*scale+10
    out.append(text(38,cursor+18,'FIELD KEY · repeated numbers belong to the same wrapped field. * No printed region.'))
    start=cursor+50
    for i,f in enumerate(fields):
        x=38+(i//13)*475;y=start+(i%13)*27
        name=f'{f["number"]:02}  {f["name"]}'+(' *' if not f['regions'] else '')
        out.append(text(x,y,name,'',f'font-size="17" fill="{f["color"] if f["regions"] else "#5b6a7c"}"'))
    out.append(text(38,start+365,'01 image name · 03 today’s date · 14 / 26 / 37 remarks are generated, not read from image text.'))
    out.append(text(38,start+393,'02 uses the printed record ID under the current pilot policy. Coordinate proposals still need approval.'))
    out.append('</svg>')
    return ''.join(out).replace('height="1480" viewBox="0 0 1480 1480"',f'height="{start+415}" viewBox="0 0 1480 {start+415}"',1).replace('width="1480" height="1480" fill=',f'width="1480" height="{start+415}" fill=',1)

