    state=json.loads((ROOT/'outputs/review-app/2d6387a71b73437fa9045600e97919a6/state.json').read_text(encoding='utf-8'))
    record=next(r for r in state['records'] if r['record_id']==RID)
    _,_,evidence=field_analysis(record,{})
    fields=[]
    for n,row in enumerate(list(b['Fields Only'].values)[1:],1):
        section,name,example,instruction=row;auto=[]
        if n in REGIONS:
            for src in evidence.get(n-1,{}).get('sources',[]):
                line=next(l for l in record['lines'] if l['id']==src['line'])
                x,y,z,t=line['source_box'];auto.append([max(FRAME[0],x+src['left']),y,min(FRAME[2],x+src['right']),t])
        fields.append(dict(number=n,name=name,section=section,color=COLORS[(n-1)%6],regions=REGIONS.get(n,[]),
            automatic_regions=auto,reference_value=str(ref[n-1]) if n>=4 and ref[n-1] is not None else None,
            status='proposal' if n in REGIONS else 'not_printed',
            instruction=instruction,detail_rules=rules.get(name,[]),manual_row=n+1,
            note=NOTES.get(n,'Source-coordinate proposal checked against the image and reference column order. It does not confirm individual characters.')))
    assert len(fields)==37 and len(REGIONS)==32
    assert all(FRAME[0]<=x<z<=FRAME[2] and FRAME[1]<=y<t<=FRAME[3] for f in fields for x,y,z,t in f['regions'])
    coverage=[]
    for line in record['lines']:
        a,b,c,d=line['source_box']
        matched=[f['number'] for f in fields if any(min(c,z)>max(a,x) and min(d,t)>max(b,y) for x,y,z,t in f['regions'])]
        coverage.append(dict(line=line['id'],fields=matched))
    assert all(c['fields'] for c in coverage)
    manifest=dict(schema_version=1,source=str(SOURCE),source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        manual=str(MANUAL),manual_sha256=hashlib.sha256(MANUAL.read_bytes()).hexdigest(),reference=str(REFERENCE),
        record_id=RID,record_label='R7',frame=FRAME,records=records,fields=fields,
        automatic_field_count=sum(bool(f['automatic_regions']) for f in fields),
        methods=dict(records='Fresh local header OCR and ruled-block detection, no reference workbook used.',
            proposals='Manually placed example coordinates, visually checked and assisted by reference workbook. Not an automatic field recognition result.',
            coordinates='Original AQ160 page pixels; left/top inclusive, right/bottom exclusive. Specific to this record.'),
        detected_line_coverage=coverage)
    (OUT/'mapping.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False),encoding='utf-8')
    (OUT/'page-records.svg').write_text(page_svg(image,records),encoding='utf-8')
